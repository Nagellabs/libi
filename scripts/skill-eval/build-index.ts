import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from "node:fs";
import { join, resolve, relative } from "node:path";
import { parseScenario } from "./scenario";
import { syncAgentSkill } from "./sync-agent-skill";
import type { ParsedScenario } from "./types";

function walk(dir: string): string[] {
  if (!existsSync(dir)) return [];
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (name.endsWith(".md")) out.push(p);
  }
  return out;
}

export function renderIndexTable(scenarios: ParsedScenario[]): string {
  const rows = [...scenarios].sort((a, b) => a.id.localeCompare(b.id));
  const header = "| id | title | skills | mcps | covers | path |\n|---|---|---|---|---|---|";
  const body = rows.map((s) =>
    `| ${s.id} | ${s.title} | ${s.skills.join(", ")} | ${s.mcps.join(", ")} | ${s.covers.join(", ")} | ${s.sourcePath} |`,
  );
  return [header, ...body].join("\n");
}

export function buildIndex(repoRoot = process.cwd()): void {
  const scenariosDir = resolve(repoRoot, "skill-eval", "scenarios");
  const files = walk(scenariosDir);
  const scenarios = files.map((f) => {
    const s = parseScenario(readFileSync(f, "utf8"), f);
    return { ...s, sourcePath: relative(repoRoot, f) };
  });
  const table = renderIndexTable(scenarios);
  const doc = [
    "# Skill-Eval Scenario Index",
    "",
    "> Generated by `npm run skill:eval:index`. Do not edit by hand.",
    "> Map a change to scenarios via the `covers` / `skills` columns, then run:",
    "> `npm run skill:eval -- skill-eval/scenarios/<group>/<file>.md`",
    "",
    table,
    "",
  ].join("\n");
  writeFileSync(resolve(repoRoot, "skill-eval", "INDEX.md"), doc);
  syncAgentSkill(repoRoot);
}

// CLI entry
if (process.argv[1] && process.argv[1].endsWith("build-index.ts")) {
  buildIndex();
  console.log("[skill-eval] INDEX.md regenerated + agent skill mirrored");
}

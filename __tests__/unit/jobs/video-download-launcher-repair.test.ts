/**
 * `video_download` runner — what happens when yt-dlp cannot even be STARTED
 * (docs-local/qa/2026-09-25-video-download-and-playback-plan.md T4/T5).
 *
 * On 2026-09-25 the owner's `~/.libi/bin/yt-dlp` exec'd an entry point inside
 * a deleted worktree: exit 126, and the agent was told to send the user to
 * Settings. The runner now answers a launch failure (exit 126/127, spawn
 * ENOENT/EACCES) with exactly ONE forced reinstall (`retryDep`) and ONE retry,
 * and marks the failure it cannot fix with `YT_DLP_UNAVAILABLE` so the tool
 * can tell it apart from yt-dlp's own errors.
 *
 * Same harness as video-download-runner.test.ts: a fake launcher script in a
 * per-test LIBI_HOME, DependencyManager and storeFile mocked. The fake
 * `retryDep` REWRITES the launcher, standing in for the real reinstall.
 */
import { describe, it, expect, vi, beforeEach, afterEach } from "vitest";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

let depCalls: string[] = [];
type DepOpts = { signal?: AbortSignal; launcherFailed?: boolean; onLauncherOnlyRepair?: () => void };
const ensureDep = vi.fn<(mcpId: string, binary: string, opts?: DepOpts) => Promise<void>>();
const retryDep = vi.fn<(mcpId: string, binary: string, opts?: DepOpts) => Promise<void>>();
vi.mock("@/mcp/registry/dependency-manager", () => ({
  DependencyManager: class {
    ensureDep(mcpId: string, binary: string, opts?: DepOpts): Promise<void> {
      depCalls.push(`ensureDep:${mcpId}/${binary}`);
      return ensureDep(mcpId, binary, opts);
    }
    retryDep(mcpId: string, binary: string, opts?: DepOpts): Promise<void> {
      depCalls.push(`retryDep:${mcpId}/${binary}`);
      return retryDep(mcpId, binary, opts);
    }
  },
}));

const storeFile = vi.fn<(a: { filename: string }) => Promise<{ id: string; filename: string }>>();
vi.mock("@/mcp/tools/file-tools", () => ({
  storeFile: (a: { filename: string }) => storeFile(a),
  mimeFromExtension: () => "video/mp4",
}));

// The SSRF guard resolves the url's host before anything spawns. A real lookup is a network round-trip this
// file cannot bound (see video-download-runner.test.ts): stub it with a public documentation address.
vi.mock("node:dns", () => ({
  promises: { lookup: vi.fn(async () => [{ address: "203.0.113.10", family: 4 }]) },
}));

import { videoDownloadRunner, YtDlpLaunchError } from "@/lib/jobs/runners/video-download";
import { YT_DLP_UNAVAILABLE } from "@/lib/video-download/launcher";

const savedHome = process.env.LIBI_HOME;
const realPlatform = process.platform;
let home: string;
const PUBLIC_URL = "https://example.com/watch?v=abc";

function launcherPath(): string {
  return path.join(home, "bin", "yt-dlp");
}

/** A launcher shaped like the one libi writes, exec'ing `target`. */
function writeLauncher(target: string): void {
  fs.mkdirSync(path.join(home, "bin"), { recursive: true });
  fs.writeFileSync(
    launcherPath(),
    `#!/bin/bash\n# Generated by libi DependencyManager.installYtDlpViaUv\n` +
      `echo x >> "${path.join(home, "spawns.txt")}"\n` +
      `exec "${target}" --no-playlist "$@"\n`,
    { mode: 0o755 },
  );
}

/** A working fake entry point: drops a file next to the `-o` template. */
function writeWorkingEntry(): string {
  const entry = path.join(home, "uv", "tools", "yt-dlp", "bin", "yt-dlp");
  fs.mkdirSync(path.dirname(entry), { recursive: true });
  fs.writeFileSync(
    entry,
    `#!/bin/bash\nOUT=""\nwhile [ $# -gt 0 ]; do if [ "$1" = "-o" ]; then OUT="$2"; shift; fi; shift; done\n` +
      `printf 'video' > "$(dirname "$OUT")/Clip.mp4"\n`,
    { mode: 0o755 },
  );
  return entry;
}

function spawnCount(): number {
  try {
    return fs.readFileSync(path.join(home, "spawns.txt"), "utf-8").trim().split("\n").length;
  } catch {
    return 0;
  }
}

function makeCtx() {
  return {
    jobId: "job-1",
    params: { url: PUBLIC_URL, pieceId: null, audioOnly: false },
    resumeState: null,
    reportProgress: () => {},
    checkpoint: async () => {},
    shouldCancel: () => false,
  };
}

beforeEach(() => {
  // The fakes are bash scripts; pin a Unix platform so the Unix spawn path is
  // what runs on every host (CI is ubuntu).
  Object.defineProperty(process, "platform", { value: "linux", configurable: true });
  home = fs.mkdtempSync(path.join(os.tmpdir(), "libi-ytdlp-repair-"));
  process.env.LIBI_HOME = home;
  depCalls = [];
  ensureDep.mockReset();
  ensureDep.mockResolvedValue(undefined);
  retryDep.mockReset();
  storeFile.mockReset();
  storeFile.mockImplementation(async (a) => ({ id: "file-1", filename: a.filename }));
});

afterEach(() => {
  Object.defineProperty(process, "platform", { value: realPlatform, configurable: true });
  process.env.LIBI_HOME = savedHome;
  fs.rmSync(home, { recursive: true, force: true });
});

describe.skipIf(realPlatform === "win32")("video_download — launcher repair", () => {
  it("repairs once and retries once when the launcher's target is gone (exit 126/127), then succeeds", async () => {
    // The owner's state: a launcher exec'ing a path that no longer exists.
    writeLauncher(path.join(home, "worktrees", "deleted", "uv", "tools", "yt-dlp", "bin", "yt-dlp"));
    retryDep.mockImplementation(async () => {
      writeLauncher(writeWorkingEntry());
    });

    const result = await videoDownloadRunner.run(makeCtx() as never);

    expect(result).toMatchObject({ fileId: "file-1", filename: "Clip.mp4" });
    expect(depCalls).toEqual([
      "ensureDep:youtube-download/uv",
      "ensureDep:youtube-download/yt-dlp",
      "retryDep:youtube-download/yt-dlp",
    ]);
    // Two launches: the dead one, then the repaired one.
    expect(spawnCount()).toBe(2);
    // UV-2: the repair says the launcher failed, so an intact tool venv is repaired offline (launcher only).
    expect(retryDep.mock.calls[0][2]).toMatchObject({ launcherFailed: true });
    expect(retryDep.mock.calls[0][2]?.signal).toBeInstanceOf(AbortSignal);
  });

  it("repairs once and retries once when there is no launcher at all (spawn ENOENT)", async () => {
    retryDep.mockImplementation(async () => {
      writeLauncher(writeWorkingEntry());
    });
    const result = await videoDownloadRunner.run(makeCtx() as never);
    expect(result).toMatchObject({ filename: "Clip.mp4" });
    expect(retryDep).toHaveBeenCalledTimes(1);
  });

  it("gives up after ONE repair when the launcher is still dead, with a clear marked error", async () => {
    const dead = path.join(home, "gone", "yt-dlp");
    writeLauncher(dead);
    retryDep.mockImplementation(async () => {
      writeLauncher(dead); // the "reinstall" leaves it broken
    });

    const err = await videoDownloadRunner.run(makeCtx() as never).then(
      () => null,
      (e: Error) => e,
    );

    expect(err).toBeInstanceOf(Error);
    expect(err!.message.startsWith(YT_DLP_UNAVAILABLE)).toBe(true);
    expect(err!.message).toMatch(/still could not be started after libi reinstalled it/);
    expect(err!.message).toMatch(/exit 12[67]/);
    expect((err as Error & { cause?: unknown }).cause).toBeInstanceOf(YtDlpLaunchError);
    expect(retryDep).toHaveBeenCalledTimes(1);
    expect(spawnCount()).toBe(2);
    expect(storeFile).not.toHaveBeenCalled();
  });

  // Review M6: a launcher-only repair (UV-2) that doesn't help used to be reported as "after libi reinstalled it",
  // with no reinstall ever tried. Now the real reinstall follows once, and the error says what was done.
  it("a launcher-only repair that doesn't help is followed by ONE real reinstall, and the error says both", async () => {
    const dead = path.join(home, "gone", "yt-dlp");
    writeLauncher(dead);
    retryDep
      .mockImplementationOnce(async (_m, _b, opts) => {
        writeLauncher(dead);
        opts?.onLauncherOnlyRepair?.();
      })
      .mockRejectedValueOnce(new Error("libi needs to download the Python packages for video download (a one-time step), and this computer appears to be offline. Try again when you're online."));
    const err = await videoDownloadRunner.run(makeCtx() as never).then(() => null, (e: Error) => e);
    expect(err!.message).toMatch(
      new RegExp(`^${YT_DLP_UNAVAILABLE} yt-dlp could not be started \\(.*\\); rewriting its launcher did not help, and reinstalling it failed: libi needs to download`),
    );
    expect(retryDep).toHaveBeenCalledTimes(2);
    expect(retryDep.mock.calls[1][2]).not.toHaveProperty("launcherFailed");
    expect(spawnCount()).toBe(2);
  });

  it("…and when the reinstall works, the third launch downloads", async () => {
    const dead = path.join(home, "gone", "yt-dlp");
    writeLauncher(dead);
    retryDep
      .mockImplementationOnce(async (_m, _b, opts) => {
        writeLauncher(dead);
        opts?.onLauncherOnlyRepair?.();
      })
      .mockImplementationOnce(async () => {
        writeLauncher(writeWorkingEntry());
      });
    const result = await videoDownloadRunner.run(makeCtx() as never);
    expect(result).toMatchObject({ filename: "Clip.mp4" });
    expect(spawnCount()).toBe(3);
  });

  it("…and when even that can't start it, the error says the launcher was rewritten AND yt-dlp reinstalled", async () => {
    const dead = path.join(home, "gone", "yt-dlp");
    writeLauncher(dead);
    retryDep.mockImplementation(async (_m, _b, opts) => {
      writeLauncher(dead);
      opts?.onLauncherOnlyRepair?.();
    });
    const err = await videoDownloadRunner.run(makeCtx() as never).then(() => null, (e: Error) => e);
    expect(err!.message).toMatch(/still could not be started after libi rewrote its launcher and reinstalled it/);
    expect(retryDep).toHaveBeenCalledTimes(2);
    expect(spawnCount()).toBe(3);
  });

  it("marks the failure when the repair itself fails (offline), without a second launch", async () => {
    writeLauncher(path.join(home, "gone", "yt-dlp"));
    retryDep.mockRejectedValue(new Error("Failed to fetch: https://pypi.org/simple/yt-dlp/"));

    await expect(videoDownloadRunner.run(makeCtx() as never)).rejects.toThrow(
      new RegExp(
        `^${YT_DLP_UNAVAILABLE} yt-dlp could not be started \\(.*\\) and reinstalling it failed: Failed to fetch`,
      ),
    );
    expect(spawnCount()).toBe(1);
  });

  it("does NOT repair when yt-dlp runs and fails on its own (exit 1) — that is a download error, unmarked", async () => {
    const entry = path.join(home, "uv", "tools", "yt-dlp", "bin", "yt-dlp");
    fs.mkdirSync(path.dirname(entry), { recursive: true });
    fs.writeFileSync(entry, `#!/bin/bash\necho "ERROR: [generic] Video not found" >&2\nexit 1\n`, {
      mode: 0o755,
    });
    writeLauncher(entry);

    const err = await videoDownloadRunner.run(makeCtx() as never).then(
      () => null,
      (e: Error) => e,
    );
    expect(err!.message).toMatch(/yt-dlp failed \(exit 1\).*Video not found/);
    expect(err!.message).not.toContain(YT_DLP_UNAVAILABLE);
    expect(retryDep).not.toHaveBeenCalled();
  });

  // UV-1 (G2 report M4): a job waiting on an install another libi runs used to wait out the lock's 35-min cap after
  // it was cancelled. The job's cancellation now reaches the wait as an AbortSignal.
  it("a job cancelled while it waits on an install stops waiting at once, and ends cancelled, not needs_install", async () => {
    let cancelled = false;
    ensureDep.mockImplementation(
      (_m, _b, opts) =>
        new Promise<void>((_resolve, reject) => {
          opts?.signal?.addEventListener("abort", () => reject(Object.assign(new Error("stopped waiting"), { name: "AbortError" })));
        }),
    );
    const run = videoDownloadRunner.run({ ...makeCtx(), shouldCancel: () => cancelled } as never).then(
      () => null,
      (e: Error) => e,
    );
    await new Promise((r) => setTimeout(r, 50));
    const at = Date.now();
    cancelled = true;
    const err = await run;
    expect(Date.now() - at).toBeLessThan(1_000);
    expect(err?.message).toBe("cancelled");
    expect(ensureDep.mock.calls[0][2]?.signal).toBeInstanceOf(AbortSignal);
  });

  it("marks an install failure from ensureDep as unavailable too", async () => {
    ensureDep.mockImplementation(async (_m, binary) => {
      if (binary === "uv") throw new Error("getaddrinfo ENOTFOUND github.com");
    });
    await expect(videoDownloadRunner.run(makeCtx() as never)).rejects.toThrow(
      `${YT_DLP_UNAVAILABLE} installing uv (needed to download videos) failed: getaddrinfo ENOTFOUND github.com`,
    );
  });
});
